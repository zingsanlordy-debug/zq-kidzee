// Safe translation getters
export function getTranslatedStory(story: StoryVideo, langCode: string) {
  // Check rich multilingual content first
  const multi = STORY_MULTILINGUAL[story.id]?.[langCode];
  if (multi) {
    return {
      title: multi.title,
      summary: multi.summary,
      moral: multi.moral,
      fullStory: multi.lines ? multi.lines.join(' ') : story.fullStory,
      lines: multi.lines || story.lines,
      questions: multi.questions || story.questions
    };
  }

  if (langCode === 'hi') {
    return {
      title: story.title,
      summary: story.summary,
      moral: story.moral,
      fullStory: story.fullStory,
      lines: story.lines,
      questions: story.questions
    };
  }
  if (langCode === 'en') {
    return {
      title: story.englishTitle || story.title,
      summary: story.summary,
      moral: story.moral,
      fullStory: story.fullStory,
      lines: story.lines,
      questions: story.questions
    };
  }

  const custom = STORY_TRANSLATIONS[story.id]?.[langCode];
  if (custom) {
    return {
      title: custom.title,
      summary: custom.summary,
      moral: custom.moral,
      fullStory: `${custom.summary} (${story.title})`,
      lines: story.lines,
      questions: story.questions
    };
  }

  // Fallback with language label
  return {
    title: `${story.title} (${story.englishTitle})`,
    summary: story.summary,
    moral: story.moral,
    fullStory: story.fullStory,
    lines: story.lines,
    questions: story.questions
  };
}

export function getTranslatedLori(lori: LoriItem, langCode: string) {
  const multi = LORI_MULTILINGUAL[lori.id]?.[langCode];
  if (multi) {
    return {
      title: multi.title,
      lyrics: multi.lyrics,
      lines: multi.lines || (multi.lyrics ? multi.lyrics.split('\n').filter(Boolean) : undefined)
    };
  }

  if (langCode === 'hi') {
    return {
      title: lori.title,
      lyrics: lori.hindiLyrics,
      lines: lori.paragraphs
    };
  }
  if (langCode === 'en') {
    return {
      title: lori.title,
      lyrics: lori.englishMeaning || lori.hindiLyrics,
      lines: lori.paragraphs
    };
  }
  const custom = LORI_TRANSLATIONS[lori.id]?.[langCode];
  if (custom) {
    return {
      title: custom.title,
      lyrics: custom.lyrics,
      lines: custom.lyrics.split('\n').filter(Boolean)
    };
  }
  return {
    title: lori.title,
    lyrics: lori.hindiLyrics,
    lines: lori.paragraphs
  };
}

