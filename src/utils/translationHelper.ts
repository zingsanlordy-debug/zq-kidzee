export function getTranslatedGk(gk: GkItem | any, langCode: string) {
  if (langCode === 'hi') {
    return { title: gk.title, detail: gk.detail, keyFact: gk.keyFact };
  }
  // Check inline translations first
  const inline = gk.translations?.[langCode];
  if (inline) {
    return { title: inline.title || gk.title, detail: inline.detail || gk.detail, keyFact: inline.keyFact || gk.keyFact };
  }
  const custom = GK_TRANSLATIONS[gk.id]?.[langCode];
  if (custom) {
    return { title: custom.title, detail: custom.detail, keyFact: custom.keyFact };
  }
  return {
    title: gk.title,
    detail: gk.detail,
    keyFact: gk.keyFact
  };
}

